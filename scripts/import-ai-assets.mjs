#!/usr/bin/env node
/**
 * Import AI-generated illustrative images into the site.
 *
 *   npm run ai-assets:import -- <folder-with-generated-images>
 *
 * For every slot in src/config/ai-slots.json, looks for a file in <folder>
 * named after the slot or its target file (any of .jpg .jpeg .png .webp .avif),
 * converts it to an optimised WebP (metadata stripped) in public/images/ai/,
 * and rewrites:
 *   - src/config/ai-assets.manifest.json   (which slots exist + dimensions)
 *   - supabase/ai_gallery_seed.sql          (flagged, replaceable gallery rows)
 *   - docs/AI_IMAGE_MANIFEST.md             (asset register)
 *
 * It also accepts `--doc-only` to just regenerate the asset register.
 */
import fs from "node:fs";
import path from "node:path";
import sharp from "sharp";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1")), "..");
const { style, slots } = JSON.parse(fs.readFileSync(path.join(root, "src/config/ai-slots.json"), "utf8"));
const manifestPath = path.join(root, "src/config/ai-assets.manifest.json");
const outDir = path.join(root, "public/images/ai");
const args = process.argv.slice(2);
const docOnly = args.includes("--doc-only");
const source = args.find((a) => !a.startsWith("--"));

const EXTS = [".webp", ".jpg", ".jpeg", ".png", ".avif"];
const MAX_WIDTH = { "16:9": 2560, "3:2": 2000, "5:4": 1800, "4:5": 1600, "1:1": 1600 };
const GALLERY_CATEGORY = {
  "gallery-01": "wedding", "gallery-02": "couple-portraits", "gallery-03": "wedding", "gallery-04": "wedding",
  "gallery-05": "reception", "gallery-06": "couple-portraits", "gallery-07": "wedding", "gallery-08": "wedding",
};

const existing = fs.existsSync(manifestPath) ? JSON.parse(fs.readFileSync(manifestPath, "utf8")).assets : [];
const bySlot = new Map(existing.map((a) => [a.slot, a]));

if (!docOnly) {
  if (!source || !fs.existsSync(source)) {
    console.error("Usage: npm run ai-assets:import -- <folder-with-generated-images>");
    process.exit(1);
  }
  fs.mkdirSync(outDir, { recursive: true });
  const files = fs.readdirSync(source);
  let imported = 0;
  for (const s of slots) {
    const base = s.file.replace(/\.webp$/, "");
    const match = files.find((f) => EXTS.includes(path.extname(f).toLowerCase()) && [s.slot, base].includes(path.basename(f, path.extname(f)).toLowerCase()));
    if (!match) continue;
    const target = path.join(outDir, s.file);
    const info = await sharp(path.join(source, match))
      .rotate()
      .resize({ width: MAX_WIDTH[s.ratio] ?? 1800, withoutEnlargement: true })
      .webp({ quality: 82, effort: 5 })
      .toFile(target);
    bySlot.set(s.slot, { slot: s.slot, file: s.file, width: info.width, height: info.height });
    imported += 1;
    console.log(`✓ ${s.slot.padEnd(28)} ← ${match}  (${info.width}×${info.height}, ${Math.round(info.size / 1024)} KB)`);
  }
  // Drop manifest entries whose file no longer exists.
  for (const [slot, a] of bySlot) if (!fs.existsSync(path.join(outDir, a.file))) bySlot.delete(slot);
  const assets = slots.flatMap((s) => (bySlot.has(s.slot) ? [bySlot.get(s.slot)] : []));
  fs.writeFileSync(manifestPath, JSON.stringify({ generatedBy: "scripts/import-ai-assets.mjs", assets }, null, 2) + "\n");
  console.log(`\nImported ${imported} file(s). ${assets.length}/${slots.length} slots now have AI images.`);
  const missing = slots.filter((s) => !bySlot.has(s.slot)).map((s) => s.slot);
  if (missing.length) console.log(`Missing: ${missing.join(", ")}`);

  // Gallery seed: flagged rows the admin can unpublish, delete or replace.
  const gallery = assets.filter((a) => a.slot.startsWith("gallery-"));
  const sql = [
    "-- Generated by scripts/import-ai-assets.mjs — AI-generated illustrative gallery items.",
    "-- Flagged is_ai_generated / is_placeholder so they can be identified and replaced in Admin › Gallery.",
    "-- Safe to re-run: skips items that already exist.",
    ...gallery.map((a, i) => {
      const def = slots.find((s) => s.slot === a.slot);
      const ref = `static/ai/${a.file}`;
      const alt = def.alt.replace(/'/g, "''");
      return `insert into public.gallery_media (media_type, storage_path, width, height, alt_text, category_id, sort_order, is_published, is_ai_generated, is_placeholder)
select 'photo', '${ref}', ${a.width}, ${a.height}, '${alt}', (select id from public.gallery_categories where slug = '${GALLERY_CATEGORY[a.slot] ?? "wedding"}'), ${9000 + i * 10}, true, true, true
where not exists (select 1 from public.gallery_media where storage_path = '${ref}');`;
    }),
  ].join("\n\n");
  fs.writeFileSync(path.join(root, "supabase/ai_gallery_seed.sql"), sql + "\n");
}

// Asset register.
const present = new Set(JSON.parse(fs.readFileSync(manifestPath, "utf8")).assets.map((a) => a.slot));
const doc = [
  "# AI Image Manifest",
  "",
  "Illustrative images of a **fictional** couple, used until real photographs are uploaded. They are not photographs of Priya and Arjun.",
  "They are flagged as AI-generated in the admin (Media page and Gallery) and any real upload in the same slot takes precedence.",
  "",
  "Generated with `scripts/import-ai-assets.mjs`. Workflow:",
  "",
  "1. Generate each image below with your preferred image model, using the shared style plus the slot prompt.",
  "2. Save files named after the slot (e.g. `hero.png`) or the target file in one folder.",
  "3. Run `npm run ai-assets:import -- <folder>` — converts to WebP into `public/images/ai/` and updates the manifest.",
  "4. Run `supabase/ai_gallery_seed.sql` in Supabase to add the flagged gallery items.",
  "",
  "**Shared style:** " + style,
  "",
  "| Slot | File | Ratio | Used for | Status | Prompt |",
  "|---|---|---|---|---|---|",
  ...slots.map((s) => `| \`${s.slot}\` | \`${s.file}\` | ${s.ratio} | ${s.usedFor} | ${present.has(s.slot) ? "✅ present" : "— missing"} | ${s.prompt.replace(/\|/g, "/")} |`),
  "",
].join("\n");
fs.writeFileSync(path.join(root, "docs/AI_IMAGE_MANIFEST.md"), doc);
console.log("Wrote docs/AI_IMAGE_MANIFEST.md");
